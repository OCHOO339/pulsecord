// Refresh the pinned Apple emoji metadata; no user data or runtime downloads here.
import { mkdir, writeFile } from 'node:fs/promises';
const revision = 'e77759c296ed37beb0dbd63908b43d8619509c6d';
const response = await fetch(`https://raw.githubusercontent.com/iamcal/emoji-data/${revision}/emoji.json`);
if (!response.ok) throw Error(`Emoji metadata returned ${response.status}`);
const entries = await response.json();
const unicode = value => String.fromCodePoint(...value.split('-').map(part => parseInt(part, 16)));
const emojis = [];
for (const entry of entries) {
    if (entry.has_img_apple) emojis.push({ image: entry.image, unicode: [...new Set([entry.unified, entry.non_qualified].filter(Boolean).map(unicode))], names: entry.short_names });
    for (const [tone, variation] of Object.entries(entry.skin_variations || {})) {
        if (!variation.has_img_apple) continue;
        const suffix = tone.split('-').map(code => `:skin-tone-${parseInt(code, 16) - 0x1f3fb + 2}`).join(':');
        emojis.push({ image: variation.image, unicode: [unicode(variation.unified)], names: entry.short_names.map(name => `${name}:${suffix}`) });
    }
}
await mkdir('packages/iosEmojis', { recursive: true });
await writeFile('packages/iosEmojis/data.ts', `// Generated by scripts/update-ios-emojis.mjs from iamcal/emoji-data (MIT metadata).\nexport const revision = ${JSON.stringify(revision)};\nexport const emojis = ${JSON.stringify(emojis)};\n`);
console.log(`Prepared ${emojis.length} Apple emoji images including skin tones.`);
